#!/usr/bin/env node
// Mirrors the shipped int8 header into a TypeScript module for the fallback path.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const header = readFileSync(resolve(here, "src/risk_model_weights.h"), "utf8");
const outPath = resolve(here, "../../src/lib/mission/riskModelWeights.ts");

function array(name) {
  const match = header.match(new RegExp(`static const \\w+ ${name}\\[(\\d+)\\] = \\{([\\s\\S]*?)\\};`));
  if (!match) throw new Error(`missing ${name}`);
  return [...match[2].matchAll(/-?\d+/g)].map((m) => Number(m[0]));
}

function float(name) {
  const match = header.match(new RegExp(`static constexpr \\w+ ${name} = (-?[0-9.]+)f?;`));
  if (!match) throw new Error(`missing ${name}`);
  return Number(match[1]);
}

function int(name) {
  const match = header.match(new RegExp(`static constexpr \\w+ ${name} = (-?[0-9]+);`));
  if (!match) throw new Error(`missing ${name}`);
  return Number(match[1]);
}

const model = {
  INPUT_SIZE: int("INPUT_SIZE"),
  HIDDEN1_SIZE: int("HIDDEN1_SIZE"),
  HIDDEN2_SIZE: int("HIDDEN2_SIZE"),
  OUTPUT_SIZE: int("OUTPUT_SIZE"),
  INPUT_SCALE: float("INPUT_SCALE"),
  INPUT_ZERO_POINT: int("INPUT_ZERO_POINT"),
  L1_OUT_SCALE: float("L1_OUT_SCALE"),
  L1_OUT_ZERO_POINT: int("L1_OUT_ZERO_POINT"),
  L2_OUT_SCALE: float("L2_OUT_SCALE"),
  L2_OUT_ZERO_POINT: int("L2_OUT_ZERO_POINT"),
  L1_W_SCALE: float("L1_W_SCALE"),
  L2_W_SCALE: float("L2_W_SCALE"),
  L3_W_SCALE: float("L3_W_SCALE"),
  W1: array("W1"),
  B1: array("B1"),
  W2: array("W2"),
  B2: array("B2"),
  W3: array("W3"),
  B3: array("B3"),
};

const body = `// AUTO-GENERATED by wasm/hyperwatch/extract-weights.mjs. Do not edit by hand.
// Mirrors firmware/HyperWatchCore/src/risk_model_weights.h (model v1.0).
export const RISK_MODEL = ${JSON.stringify(model, null, 2)} as const;

export const RISK_MODEL_VERSION = "HyperWatch Risk MLP v1.0 (int8 13-16-8-6)";
`;

writeFileSync(outPath, body);
console.log(`wrote ${outPath}`);
